check <- function(id, result, evidence) {
  results[[id]] <<- list(pass = isTRUE(result), evidence = evidence)
  cat("CHECK", id, if (isTRUE(result)) "PASS" else "FAIL", jsonlite::toJSON(evidence, auto_unbox = TRUE), "\n")
  jsonlite::write_json(results, args[3], pretty = TRUE, auto_unbox = TRUE)
}
mat_error <- function(a,b) {
 if (!identical(dim(a),dim(b)) || !identical(is.na(a),is.na(b))) return(Inf)
 max(abs(a-b),na.rm=TRUE)
}
